import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const versionPath = join(root, 'design-system/version.json')
const tokensPath = join(root, 'src/design-system/tokens.css')
const brandManifestPath = join(root, 'design-system/brand-manifest.json')
const version = JSON.parse(readFileSync(versionPath, 'utf8'))

if (!/^\d+\.\d+\.\d+$/.test(version.version)) throw new Error('Design System version must be SemVer')
if (!/^[a-f0-9]{40}$/.test(version.sourceCommit)) throw new Error('Design System sourceCommit must be a full commit SHA')
if (!version.artifact.includes('glucontinuum-design-system-')) throw new Error('Design System artifact is invalid')
if (!existsSync(tokensPath)) throw new Error('Generated Design System CSS snapshot is missing')
const css = readFileSync(tokensPath, 'utf8')
if (!css.startsWith('/* Generated by scripts/generate-tokens.mjs. Do not edit. */')) {
  throw new Error('Generated Design System CSS header must use valid CSS comment syntax')
}
for (const token of [
  '--brand-primary',
  '--brand-on-primary',
  '--surface-canvas',
  '--surface-default',
  '--surface-raised',
  '--text-primary',
  '--text-secondary',
  '--border-subtle',
  '--focus-indicator',
  '--status-in-range',
  '--space-12',
  '--radius-lg',
  '--component-card-radius',
  '--component-button-radius',
  '--typography-size-body',
  '--typography-size-display',
  '--layout-screen-padding',
  '--layout-touch-target',
]) {
  if (!css.includes(token)) throw new Error('Design System token is missing: ' + token)
}
if (!css.includes('[data-theme="dark"]')) throw new Error('Design System dark theme tokens are missing')
if (css.includes('main')) throw new Error('Design System snapshot must not reference main')

if (!existsSync(brandManifestPath)) throw new Error('Generated Design System brand manifest is missing')
const brandManifest = JSON.parse(readFileSync(brandManifestPath, 'utf8'))
const appMark = brandManifest.outputs?.find((output) => output.name === 'app' && output.platforms?.includes('web'))
if (!appMark || appMark.file !== 'glucontinuum-mark-app.svg') {
  throw new Error('Design System brand manifest must define the generated web app mark')
}
const faviconPath = join(root, 'public/favicon.svg')
if (!existsSync(faviconPath)) throw new Error('Generated Design System favicon is missing')
const favicon = readFileSync(faviconPath, 'utf8')
if (!favicon.includes('Generated from assets/brand/glucontinuum-mark-master.svg')) {
  throw new Error('Favicon is not the generated Design System app mark')
}

console.log('Validated Design System v' + version.version + ' and generated brand assets from ' + version.sourceCommit)
